// Token Radar's model: one sealed snapshot of the protocol universe in, one ranked board out.
//
// The board ranks every protocol the snapshot's record shows as pre-token and rankable: the whole
// watchlist (the floor, never a ceiling) plus every early protocol below the floor that is not a
// wrapped, staked or bridged product of a token that already trades. Protocols whose token already
// trades are kept apart in the Live view with the market's own values, never mixed into the ranking.
//
// Implied value follows only from the snapshot's own figures. The base multiple is not a guess: it is
// calibrated from the snapshot itself, the median market-cap-to-TVL ratio of the live-token protocols
// in the same file, clamped to a sane band. Then:
//
//   growth    = clamp(change_7d, -60, 120) per cent (null reads as 0)
//   growthMult   = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity  = 0.55 + 0.45 x sqrt(min(age_days, 1460) / 1460)   (age unknown: 365 days)
//   breadth   = 1 + 0.02 x min(chains - 1, 5)
//   implied   = max(1, round(tvl_usd x baseMultiple x growthMult x maturity x breadth))
//
// No protocol name is ever special-cased: the same function scores every row, and the dashboard's
// model.js recomputes every row from the same figures so the page and the board agree.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
